// Writes .env.preprod (laptop) or .env.coolify (Coolify) with fresh random secrets. Usage:
//   node scripts/preprod-env.mjs [--host 192.168.1.20] [--force]
//   node scripts/preprod-env.mjs --coolify [--domain enzointeriors.co.uk] [--force]
// --host = the address other devices use to reach this machine (default localhost).
// --coolify = hosts web preprod.<domain>, admin-/portal-/api-/media-/mail-preprod.<domain>, https.
import { randomBytes } from 'node:crypto';
import { existsSync, writeFileSync } from 'node:fs';

const arg = (n) => {
  const i = process.argv.indexOf(`--${n}`);
  return i < 0 ? null : (process.argv[i + 1] ?? true);
};
const host = arg('host') || 'localhost';
if (!/^[\w.-]+$/.test(host)) throw new Error(`Bad --host: ${host}`);
const coolify = !!arg('coolify');
const domain = arg('domain') || 'enzointeriors.co.uk';
if (!/^[\w.-]+$/.test(domain)) throw new Error(`Bad --domain: ${domain}`);
const file = coolify ? '.env.coolify' : '.env.preprod';
const out = new URL(`../${file}`, import.meta.url);
if (existsSync(out) && !arg('force')) {
  console.error(`${file} exists. --force replaces it (new passwords: wipe the volumes if the database already exists).`);
  process.exit(1);
}
// URL- and shell-safe random string of n characters.
const rnd = (n) => randomBytes(n * 2).toString('base64').replace(/[^A-Za-z0-9]/g, '').slice(0, n);
const adminPassword = rnd(20);
const urls = coolify
  ? `# Hosts Traefik routes (docker-compose.coolify.yml) and the https addresses browsers use.
# Point each at your Coolify server in DNS / the Cloudflare tunnel. Redeploy with a rebuild after changing them.
WEB_HOST=preprod.${domain}
ADMIN_HOST=admin-preprod.${domain}
PORTAL_HOST=portal-preprod.${domain}
API_HOST=api-preprod.${domain}
MEDIA_HOST=media-preprod.${domain}
MAIL_HOST=mail-preprod.${domain}
WEB_PUBLIC_URL=https://preprod.${domain}
ADMIN_URL=https://admin-preprod.${domain}
PORTAL_URL=https://portal-preprod.${domain}
API_PUBLIC_URL=https://api-preprod.${domain}
MEDIA_BASE_URL=https://media-preprod.${domain}/enzo-public
TRUST_PROXY=1
# Mailpit shows every email (sign-in codes included) at https://mail-preprod.${domain}: keep it behind Cloudflare Access.`
  : `# Addresses a browser uses (host: ${host}). Rebuild (up --build) after changing them.
WEB_PUBLIC_URL=http://${host}:13000
ADMIN_URL=http://${host}:15174
PORTAL_URL=http://${host}:15175
API_PUBLIC_URL=http://${host}:14000
MEDIA_BASE_URL=http://${host}:19000/enzo-public
# Mail goes to Mailpit: http://${host}:18025.`;

writeFileSync(
  out,
  `# Pre-prod only. Generated by scripts/preprod-env.mjs: random values, safe to regenerate. Not committed.
${coolify ? '# Paste into the Coolify resource Environment Variables (compose: docker-compose.coolify.yml).' : '# docker compose --env-file .env.preprod -f docker-compose.preprod.yml up -d --build --wait'}

POSTGRES_USER=enzo
POSTGRES_DB=enzo
POSTGRES_PASSWORD=${rnd(24)}

JWT_SECRET=${rnd(64)}
APP_ENCRYPTION_KEY=${randomBytes(32).toString('base64')}
REVALIDATE_SECRET=${rnd(32)}
ALERT_SHARED_SECRET=${rnd(32)}

# First admin, created on first boot. Its sign-in codes arrive in Mailpit.
ADMIN_EMAIL=admin@enzo.test
ADMIN_PASSWORD=${adminPassword}
ADMIN_NAME=Pre-prod Admin

S3_ACCESS_KEY_ID=preprod${rnd(10)}
S3_SECRET_ACCESS_KEY=${rnd(32)}

${urls}
# Empty = alerts go to the Admin users.
ALERT_TO=
`,
);
console.log(`Wrote ${file}${coolify ? '' : ` (host ${host})`}.\nAdmin: admin@enzo.test / ${adminPassword}`);
