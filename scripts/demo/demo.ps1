<#
  One-command local demo of the whole Enzo Interiors platform (see README.md).

    demo.cmd              build + start everything, load the mock data, print the sign-ins
    demo.cmd stop         stop the containers, keep the data
    demo.cmd info         print the accounts and URLs again
    demo.cmd reset        DELETE the demo database and uploads and the generated settings

  -PortOffset 10000       first run only: shift every published port (when 3000/4000/5174/... are busy)
#>
param(
  [ValidateSet('start', 'stop', 'info', 'reset')] [string] $Action = 'start',
  [int] $PortOffset = 0
)
$ErrorActionPreference = 'Stop'
$Root = (Resolve-Path (Join-Path $PSScriptRoot '..\..')).Path
$EnvFile = Join-Path $Root '.env.demo.local' # gitignored (.env.*.local); never the owner's .env
$Project = 'enzo-demo'                       # its own containers and volumes, apart from a dev stack
$Password = if ($env:DEMO_PASSWORD) { $env:DEMO_PASSWORD } else { 'Enzo-Demo-2026' }
Set-Location $Root

function Compose { & docker compose -p $Project --env-file $EnvFile @args; if ($LASTEXITCODE) { throw "docker compose $($args -join ' ') failed" } }
function Secret([int] $bytes) { $b = New-Object byte[] $bytes; [Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($b); [Convert]::ToBase64String($b) -replace '[+/=]', 'x' }
function Settings { $h = @{}; Get-Content $EnvFile | Where-Object { $_ -match '^[A-Z_0-9]+=' } | ForEach-Object { $k, $v = $_ -split '=', 2; $h[$k] = $v }; $h }

function New-EnvFile {
  $web, $adm, $por, $api, $pg, $redis, $minio, $console, $mp, $smtp = (3000, 5174, 5175, 4000, 5432, 6379, 9000, 9001, 8025, 1025 | ForEach-Object { $_ + $PortOffset })
  $b = New-Object byte[] 32; [Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($b)
  @"
# Generated by scripts/demo/demo.ps1 - local demo only, never commit. 'demo.cmd reset' deletes it.
COMPOSE_PROFILES=dev,db
POSTGRES_USER=enzo
POSTGRES_DB=enzo
POSTGRES_PASSWORD=$(Secret 18)
JWT_SECRET=$(Secret 48)
JWT_EXPIRES_IN=8h
REVALIDATE_SECRET=$(Secret 32)
APP_ENCRYPTION_KEY=$([Convert]::ToBase64String($b))
S3_ACCESS_KEY_ID=demo$(Secret 6)
S3_SECRET_ACCESS_KEY=$(Secret 24)
MEDIA_BASE_URL=http://localhost:$minio/enzo-public
WEB_PUBLIC_URL=http://localhost:$web
ADMIN_URL=http://localhost:$adm
PORTAL_URL=http://localhost:$por
API_PUBLIC_URL=http://localhost:$api
WEB_PORT=$web
ADMIN_PORT=$adm
PORTAL_PORT=$por
API_PORT=$api
POSTGRES_PORT=$pg
REDIS_PORT=$redis
MINIO_PORT=$minio
MINIO_CONSOLE_PORT=$console
MAILPIT_PORT=$mp
MAILPIT_SMTP_PORT=$smtp
DISABLE_2FA=true
SMTP_HOST=mailpit
SMTP_PORT=1025
MAIL_FROM=Enzo Interiors <no-reply@localhost>
ALERT_SHARED_SECRET=$(Secret 24)
"@ | Set-Content -Encoding ascii $EnvFile
}

function Show-Info {
  $s = Settings
  Write-Host ''
  Write-Host 'URLs' -ForegroundColor Green
  '  Public site      http://localhost:{0}' -f $s.WEB_PORT
  '  Admin            http://localhost:{0}' -f $s.ADMIN_PORT
  '  Client portal    http://localhost:{0}' -f $s.PORTAL_PORT
  '  API health       http://localhost:{0}/health' -f $s.API_PORT
  '  Mailpit          http://localhost:{0}   (every email the system sends lands here)' -f $s.MAILPIT_PORT
  '  MinIO console    http://localhost:{0}   (login: {1} / {2})' -f $s.MINIO_CONSOLE_PORT, $s.S3_ACCESS_KEY_ID, $s.S3_SECRET_ACCESS_KEY
  Write-Host ''
  Write-Host "Sign-ins - the password for every account is: $Password" -ForegroundColor Green
  Write-Host '  Two-step sign-in is OFF.'
  Write-Host '  Admin app (staff):'
  'admin:Admin', 'admin2:Admin (second one, has a pending removal request)', 'infra:Infra manager (platform only, no client data)',
    'designer:Designer', 'designer2:Designer', 'installer:Installer', 'editor:Editor (CMS only)' |
    ForEach-Object { $k, $v = $_ -split ':', 2; '    {0,-30} {1}' -f "$k@enzo-mock.test", $v }
  Write-Host '  Client portal:'
  '    sarah@enzo-mock.test           Sarah Jones (kitchen + wardrobe)'
  '    tom@enzo-mock.test             Tom & Lucy Whitfield (media wall + loft bedroom)'
  '    raj@, oliver@, zoe@, bulk0@, bulk2@, bulk4@, bulk6@enzo-mock.test also sign in'
  '    (emma@ and new@ have no portal access; inactive@ is Inactive and is refused)'
  Write-Host ''
  Write-Host 'The Mail page needs a Google OAuth client this demo does not have (see README). Outgoing email works: read it in Mailpit.' -ForegroundColor Yellow
  Write-Host ''
}

switch ($Action) {
  'stop' { if (Test-Path $EnvFile) { Compose stop; Write-Host 'Stopped. Data kept; demo.cmd starts it again.' } else { Write-Host 'Nothing to stop.' }; return }
  'info' { if (-not (Test-Path $EnvFile)) { throw 'No demo yet: run demo.cmd first.' }; Show-Info; return }
  'reset' {
    if (Test-Path $EnvFile) {
      if ((Read-Host 'This DELETES the demo database, uploads and settings. Type "wipe" to continue') -ne 'wipe') { Write-Host 'Cancelled.'; return }
      Compose down --volumes --remove-orphans
      Remove-Item $EnvFile
    }
    Write-Host 'Demo wiped. demo.cmd builds a fresh one.'
    return
  }
}

# ---- start -----------------------------------------------------------------
if (-not (Get-Command docker -ErrorAction SilentlyContinue)) { throw 'Docker is not installed or not on PATH.' }
& docker info *> $null; if ($LASTEXITCODE) { throw 'Docker is not running: start Docker Desktop and try again.' }
if (-not (docker network ls --format '{{.Name}}' | Where-Object { $_ -eq 'coolify' })) { docker network create coolify | Out-Null }

$fresh = -not (Test-Path $EnvFile)
if ($fresh) { New-EnvFile } elseif ($PortOffset) { Write-Host 'Ignoring -PortOffset: ports were fixed when the demo was created (demo.cmd reset to change).' -ForegroundColor Yellow }
$s = Settings

# A port held by something that is not this demo stops us before a half-started stack.
if (-not @(docker ps --filter "label=com.docker.compose.project=$Project" -q).Count) {
  $busy = 'WEB_PORT', 'ADMIN_PORT', 'PORTAL_PORT', 'API_PORT', 'POSTGRES_PORT', 'REDIS_PORT', 'MINIO_PORT', 'MINIO_CONSOLE_PORT', 'MAILPIT_PORT', 'MAILPIT_SMTP_PORT' |
    Where-Object { Get-NetTCPConnection -State Listen -LocalPort ([int] $s[$_]) -ErrorAction SilentlyContinue } | ForEach-Object { "$_=$($s[$_])" }
  if ($busy) {
    if ($fresh) { Remove-Item $EnvFile }
    throw "Ports already in use: $($busy -join ', '). Stop what holds them (another docker compose stack, or dev servers), or run: demo.cmd -PortOffset 10000"
  }
}

Write-Host 'Building and starting the stack (the first build takes several minutes)...' -ForegroundColor Cyan
Compose up -d --build --wait

Write-Host 'Loading the mock data...' -ForegroundColor Cyan
Compose run --rm -e "MOCK_PASSWORD=$Password" seed npm run mock:seed | Out-Null

# A fresh database says "coming soon" and hides most pages; a demo should show the whole site.
$api = "http://localhost:$($s.API_PORT)"
$login = Invoke-RestMethod -Method Post "$api/auth/admin/login" -ContentType 'application/json' -Body (@{ email = 'admin@enzo-mock.test'; password = $Password } | ConvertTo-Json)
$h = @{ Authorization = "Bearer $($login.access_token)" }
$site = Invoke-RestMethod "$api/settings" -Headers $h
if ($site.status -ne 'live') {
  $body = @{ status = 'live'; launch_at = $null; notification_emails = @($site.notification_emails | Where-Object { $_ })
             pages = @{ about = $true; services = $true; portfolio = $true; booking = $true; contact = $true } } | ConvertTo-Json
  Invoke-RestMethod -Method Put "$api/settings" -Headers $h -ContentType 'application/json' -Body $body | Out-Null
  Write-Host 'Website switched to live, with its pages on.'
}

Write-Host "`nDemo is running." -ForegroundColor Green
Show-Info
Write-Host 'demo.cmd stop keeps the data   |   demo.cmd reset wipes it' -ForegroundColor DarkGray
